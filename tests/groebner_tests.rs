#[test]
fn pauli_algebra_exact() {
    let (alg, rels) = relations::pauli::<CQ>(1);
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(gb.is_complete());
    assert!(gb.verify(None).is_empty());
    let q = QuotientAlgebra::new(gb.clone());
    assert_eq!(q.dimension(), Some(4));
    assert_eq!(q.hilbert_series(2), vec![1, 3, 0]);
    // X Y Z = i
    let xyz: Polynomial<CQ> = alg.parse("X0*Y0*Z0").unwrap();
    let i: Polynomial<CQ> = alg.parse("i").unwrap();
    assert_eq!(gb.reduce(&xyz), i);
    // {X, Y} = 0, [X, Y] = 2 i Z
    let x: Polynomial<CQ> = alg.gen("X0");
    let y: Polynomial<CQ> = alg.gen("Y0");
    assert!(gb.reducer().reduce_anticommutator(&x, &y).is_zero());
    assert_eq!(gb.reduce_commutator(&x, &y), alg.parse("2*i*Z0").unwrap());

    // two qubits
    let (alg2, rels2) = relations::pauli::<CQ>(2);
    let gb2 = GroebnerBasis::compute(rels2, &GroebnerOptions::default());
    assert!(gb2.is_complete());
    let q2 = QuotientAlgebra::new(gb2.clone());
    assert_eq!(q2.dimension(), Some(16));
    assert_eq!(q2.hilbert_series(3), vec![1, 6, 9, 0]);
    // Bell-type check: (X0 X1)(Z0 Z1) = (X0 Z0)(X1 Z1) = (-i Y0)(-i Y1) = -Y0 Y1
    let xx: Polynomial<CQ> = alg2.parse("X0*X1").unwrap();
    let zz: Polynomial<CQ> = alg2.parse("Z0*Z1").unwrap();
    assert_eq!(gb2.reduce_product(&xx, &zz), alg2.parse("-Y0*Y1").unwrap());
    assert!(gb2.reduce_commutator(&xx, &zz).is_zero());
}

#[test]
fn pauli_algebra_floating_point() {
    let (alg, rels) = relations::pauli::<Complex<f64>>(2);
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(gb.is_complete());
    let q = QuotientAlgebra::new(gb.clone());
    assert_eq!(q.dimension(), Some(16));
    // same leading words as the exact computation
    let (_, rels_exact) = relations::pauli::<CQ>(2);
    let gb_exact = GroebnerBasis::compute(rels_exact, &GroebnerOptions::default());
    assert_eq!(gb.leading_words(), gb_exact.leading_words());
    let p: Polynomial<Complex<f64>> = alg.parse("(X0 + Y1)^4").unwrap();
    let nf = gb.reduce(&p);
    // (X0 + Y1)^2 = 2 + 2 X0 Y1, so the fourth power is 8 + 8 X0 Y1
    let expected: Polynomial<Complex<f64>> = alg.parse("8 + 8*X0*Y1").unwrap();
    assert!(nf.approx_eq(&expected, 1e-9), "{}", nf);
}

#[test]
fn clifford_type_algebras() {
    let (_, rels) = relations::majorana::<Q>(4);
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(gb.is_complete());
    let q = QuotientAlgebra::new(gb);
    assert_eq!(q.hilbert_series(5), vec![1, 4, 6, 4, 1, 0]);
    assert_eq!(q.dimension(), Some(16));

    let (_, rels) = relations::exterior::<Q>(3);
    let q = QuotientAlgebra::from_relations(rels, &GroebnerOptions::default());
    assert_eq!(q.dimension(), Some(8));

    let (alg, rels) = relations::clifford::<Q>(&[1, -1]);
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    let g01 = rat(&alg, "g0*g1");
    // (g0 g1)^2 = -g0^2 g1^2 = -(1)(-1) = 1
    assert_eq!(gb.reduce_pow(&g01, 2), alg.one());
}

#[test]
fn infinite_basis_is_truncated_and_resumable() {
    let alg = FreeAlgebra::new(["x", "y"]);
    let f = rat(&alg, "x*y*x - x*y");
    let mut solver = GroebnerSolver::new(vec![f.clone()], GroebnerOptions::new().max_degree(6));
    let status = solver.run();
    match status {
        Termination::DegreeBound {
            bound,
            smallest_pending,
        } => {
            assert_eq!(bound, 6);
            assert_eq!(smallest_pending, 7);
        }
        other => panic!("unexpected status {:?}", other),
    }
    let gb = solver.basis();
    assert!(!gb.is_complete());
    // elements x y^n x - x y^n for n = 1..=3 (overlap words up to length 6)
    let expected: Vec<Polynomial<Q>> = (1..=3)
        .map(|n| rat(&alg, &format!("x*y^{}*x - x*y^{}", n, n)))
        .collect();
    assert_eq!(gb.elements(), &expected[..]);
    assert!(gb.verify(Some(6)).is_empty());
    assert!(gb.stats().pending_pairs > 0);

    // resume with a higher bound: more elements appear, earlier ones persist
    solver.set_options(GroebnerOptions::new().max_degree(10));
    solver.run();
    let gb2 = solver.basis();
    assert_eq!(gb2.len(), 7);
    for (i, g) in gb2.elements().iter().enumerate() {
        let n = i + 1;
        assert_eq!(*g, rat(&alg, &format!("x*y^{}*x - x*y^{}", n, n)));
    }
    assert!(gb2.verify(Some(10)).is_empty());

    // the ideal element x y^5 x - x y^5 is detected with bound 10 (overlap words up to 10 ⇒ n ≤ 7)
    assert!(gb2.contains(&rat(&alg, "x*y^5*x - x*y^5")));
    // but with the small basis it is not
    assert!(!gb.contains(&rat(&alg, "x*y^5*x - x*y^5")));
}

#[test]
fn limits_produce_partial_results() {
    let alg = FreeAlgebra::new(["x", "y"]);
    let f = rat(&alg, "x*y*x - x*y");

    let gb = GroebnerBasis::compute(vec![f.clone()], &GroebnerOptions::new().max_pairs(2));
    assert_eq!(*gb.termination(), Termination::PairLimit);
    assert!(!gb.is_empty());

    let gb = GroebnerBasis::compute(
        vec![f.clone()],
        &GroebnerOptions::new().time_limit(Duration::ZERO),
    );
    assert_eq!(*gb.termination(), Termination::TimeLimit);
    assert_eq!(gb.len(), 1);

    let flag = Arc::new(AtomicBool::new(true));
    let gb = GroebnerBasis::compute(
        vec![f.clone()],
        &GroebnerOptions::new().cancel_token(flag.clone()),
    );
    assert_eq!(*gb.termination(), Termination::Canceled);

    let gb = GroebnerBasis::compute(vec![f.clone()], &GroebnerOptions::new().max_basis_size(3));
    assert_eq!(*gb.termination(), Termination::BasisSizeLimit);
    assert_eq!(gb.len(), 3);

    // a time-limited run on an infinite basis really stops
    let start = std::time::Instant::now();
    let gb = GroebnerBasis::compute(
        vec![f],
        &GroebnerOptions::new().time_limit(Duration::from_millis(200)),
    );
    assert!(start.elapsed() < Duration::from_secs(5));
    assert!(!gb.is_complete());
    flag.store(false, Ordering::Relaxed);
}

