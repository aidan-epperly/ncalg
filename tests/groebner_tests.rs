#[test]
fn bracket_violating_jacobi_collapses() {
    // [y,x] = z, [z,x] = x, [z,y] = 0 does not satisfy Jacobi; the Jacobiator
    // z lies in the ideal, forcing x into it as well.
    let alg = FreeAlgebra::new(["x", "y", "z"]);
    let rels = relations::lie_algebra::<Q, _>(&alg, |j, i| match (j, i) {
        (1, 0) => rat(&alg, "z"),
        (2, 0) => rat(&alg, "x"),
        (2, 1) => alg.zero(),
        _ => unreachable!(),
    });
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(gb.is_complete());
    let lws: Vec<String> = gb.leading_words().iter().map(|w| alg.format_word(w)).collect();
    assert_eq!(lws, vec!["x", "z"]);
    let q = QuotientAlgebra::new(gb);
    assert_eq!(q.hilbert_series(3), vec![1, 1, 1, 1]); // K[y]
}

#[test]
fn symmetric_group_s3_has_dimension_6() {
    let (alg, rels) = relations::symmetric_group_3::<Q>();
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(gb.is_complete(), "{}", gb);
    assert!(gb.verify(None).is_empty());
    let q = QuotientAlgebra::new(gb.clone());
    assert_eq!(q.dimension(), Some(6));
    // (st)^3 = 1 in S_3
    let st = rat(&alg, "s*t");
    assert_eq!(gb.reduce_pow(&st, 3), alg.one());
    assert_ne!(gb.reduce_pow(&st, 2), alg.one());
    // every word reduces to one of six normal words
    let normals = q.normal_words_up_to(10);
    assert_eq!(normals.len(), 6);
}

