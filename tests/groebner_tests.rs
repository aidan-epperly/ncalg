/// Hilbert-series counts used to wrap silently in `usize`; the free algebra
/// on 3 generators has 3^50 > 2^64 words of length 50.
#[test]
#[should_panic(expected = "overflows usize")]
fn hilbert_series_overflow_is_reported() {
    // z^60 = 0 restricts nothing below length 60
    let alg = FreeAlgebra::new(["x", "y", "z"]);
    let rel: Polynomial<BigRational> = alg.parse("z^60").unwrap();
    let gb = GroebnerBasis::compute(vec![rel], &GroebnerOptions::default());
    let q = QuotientAlgebra::new(gb);
    let h = q.hilbert_series(40);
    assert_eq!(h[40], 3usize.pow(40));
    q.hilbert_series(50);
}

/// The qubit swap algebra on 7 qubits in f64 (generators s_ij, the
/// S_n relations and the antisymmetrizer on every triple).  Rounding residue
/// used to pass the per-merge cancellation test and collapse the basis to
/// {1}; the exact basis has 796 elements.
#[test]
fn f64_qubit_swap_basis_does_not_collapse() {
    let n = 7;
    let names: Vec<String> = (0..n)
        .flat_map(|i| (i + 1..n).map(move |j| format!("s{i}_{j}")))
        .collect();
    let alg = FreeAlgebra::new(names);
    let g = |i: usize, j: usize| alg.gen::<f64>(&format!("s{}_{}", i.min(j), i.max(j)));
    let one: Polynomial<f64> = alg.constant(1.0);
    let mut rels = Vec::new();
    for i in 0..n {
        for j in i + 1..n {
            rels.push(&g(i, j) * &g(i, j) - &one);
            for k in 0..n {
                for l in k + 1..n {
                    if (i, j) < (k, l) && i != k && i != l && j != k && j != l {
                        rels.push(&g(i, j) * &g(k, l) - &g(k, l) * &g(i, j));
                    }
                }
            }
        }
    }
    for i in 0..n {
        for j in 0..n {
            for k in 0..n {
                if i != j && j != k && i != k {
                    rels.push(&g(i, j) * &g(j, k) - &g(i, k) * &g(i, j));
                }
            }
        }
    }
    for i in 0..n {
        for j in i + 1..n {
            for k in j + 1..n {
                let (a, b, c) = (g(i, j), g(i, k), g(j, k));
                rels.push(&one - &a - &b - &c + &a * &c + &c * &a);
            }
        }
    }
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(!gb.reducer().is_unit_ideal());
    assert_eq!(gb.len(), 796);
}

/// The float residue test is relative to the S-polynomial (the tails),
/// not to the monic elements: with tails of size 1e-6 the genuine remainder
/// 1e-12·y was dropped and y went missing from the basis.
#[test]
fn f64_small_tails_keep_genuine_remainders() {
    use ncalg::BigRational;
    let alg = FreeAlgebra::new(["x", "y", "z"]);
    let q: Vec<Polynomial<BigRational>> = vec![
        alg.parse("x*x - 1/1000000*z").unwrap(),
        alg.parse("z*x - x*z - 1/1000000*y").unwrap(),
    ];
    let f: Vec<Polynomial<f64>> = vec![
        alg.parse("x*x - 0.000001*z").unwrap(),
        alg.parse("z*x - x*z - 0.000001*y").unwrap(),
    ];
    let o = GroebnerOptions::default().max_degree(6);
    let exact = GroebnerBasis::compute(q, &o);
    let float = GroebnerBasis::compute(f, &o);
    assert_eq!(float.leading_words(), exact.leading_words());
}

/// A basis loaded without a recorded status is not trusted as
/// complete, and a run that empties its queue exactly at a limit is.
#[test]
fn completeness_is_not_assumed_or_lost() {
    let text = "ncalg v1\nkind: groebner-basis\ngenerators: x, y\norder: deglex\nadjoint: 0 1\ncoefficients: BigRational\ncount: 1\nx*y*x - x*y\n";
    let gb = ncalg::io::groebner_basis_from_str::<ncalg::BigRational>(text).unwrap();
    assert!(!gb.is_complete());
    let alg = FreeAlgebra::new(["x", "y"]);
    let p: Polynomial<ncalg::BigRational> = alg.parse("x*y - y*x").unwrap();
    let gb = GroebnerBasis::compute(vec![p], &GroebnerOptions::default().max_pairs(1));
    assert!(gb.is_complete(), "{:?}", gb.termination());
}
