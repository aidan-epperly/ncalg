//! Gröbner basis computations against known results and self-consistency.

use ncalg::relations;
use ncalg::{
    BigRational, Complex, Elimination, FreeAlgebra, GroebnerBasis, GroebnerOptions, GroebnerSolver,
    Polynomial, QuotientAlgebra, Termination, Word,
};
use rand::rngs::StdRng;
use rand::{Rng, SeedableRng};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::time::Duration;

type Q = BigRational;
type CQ = Complex<BigRational>;

fn rat(alg: &FreeAlgebra, s: &str) -> Polynomial<Q> {
    alg.parse(s).unwrap()
}

/// A random polynomial with small integer coefficients.
fn random_poly(rng: &mut StdRng, alg: &FreeAlgebra, max_len: usize, n_terms: usize) -> Polynomial<Q> {
    let n = alg.num_vars() as u32;
    let terms = (0..n_terms).map(|_| {
        let len = rng.gen_range(0..=max_len);
        let w: Vec<u32> = (0..len).map(|_| rng.gen_range(0..n)).collect();
        let c = rng.gen_range(-3i64..=3);
        (Word::from_vec(w), ncalg::Coeff::from_i64(c))
    });
    Polynomial::from_terms(alg.clone(), terms)
}

/// A random homogeneous polynomial of the given degree.
fn random_homog(rng: &mut StdRng, alg: &FreeAlgebra, deg: usize, n_terms: usize) -> Polynomial<Q> {
    let n = alg.num_vars() as u32;
    let terms = (0..n_terms).map(|_| {
        let w: Vec<u32> = (0..deg).map(|_| rng.gen_range(0..n)).collect();
        let c = rng.gen_range(-3i64..=3);
        (Word::from_vec(w), ncalg::Coeff::from_i64(c))
    });
    Polynomial::from_terms(alg.clone(), terms)
}

/// Random element of the ideal generated by `gens`.
fn random_ideal_element(
    rng: &mut StdRng,
    alg: &FreeAlgebra,
    gens: &[Polynomial<Q>],
    max_len: usize,
) -> Polynomial<Q> {
    let mut acc = alg.zero::<Q>();
    for _ in 0..4 {
        let g = &gens[rng.gen_range(0..gens.len())];
        let a = random_poly(rng, alg, max_len, 2);
        let b = random_poly(rng, alg, max_len, 2);
        acc += &a * g * &b;
    }
    acc
}

#[test]
fn commutative_relations_are_a_groebner_basis() {
    let alg = FreeAlgebra::new(["x", "y", "z"]);
    let rels = relations::commutative::<Q>(&alg);
    let gb = GroebnerBasis::compute(rels.clone(), &GroebnerOptions::default());
    assert!(gb.is_complete());
    assert_eq!(gb.len(), 3);
    assert!(gb.verify(None).is_empty());
    // normal form of (x+y+z)^3 has the 10 commutative monomials
    let s = rat(&alg, "(x + y + z)^3");
    let nf = gb.reduce(&s);
    assert_eq!(nf.num_terms(), 10);
    assert_eq!(nf.coeff_of(&[0, 1, 2]), ncalg::Coeff::from_i64(6)); // 3! * xyz
    let q = QuotientAlgebra::new(gb);
    assert_eq!(q.hilbert_series(4), vec![1, 3, 6, 10, 15]);
    assert_eq!(q.dimension(), None);
}

#[test]
fn weyl_algebra() {
    let (alg, rels) = relations::weyl::<Q>(1);
    let gb = GroebnerBasis::compute(rels, &GroebnerOptions::default());
    assert!(gb.is_complete());
    assert_eq!(gb.len(), 1);
    assert_eq!(gb.elements()[0].to_string(), "d1*x1 - x1*d1 - 1");
    let nf = gb.reduce(&rat(&alg, "d1^2*x1^2"));
    assert_eq!(nf, rat(&alg, "x1^2*d1^2 + 4*x1*d1 + 2"));
    // [d, x^n] = n x^(n-1)
    for n in 1..6u32 {
        let xn = rat(&alg, "x1").pow(n);
        let c = gb.reduce_commutator(&rat(&alg, "d1"), &xn);
        let expected = rat(&alg, "x1")
            .pow(n - 1)
            .scale(&ncalg::Coeff::from_i64(n as i64));
        assert_eq!(c, expected);
    }
    // two variables: 2 Weyl relations + 4 commutation relations
    let (_alg2, rels2) = relations::weyl::<Q>(2);
    let gb2 = GroebnerBasis::compute(rels2, &GroebnerOptions::default());
    assert!(gb2.is_complete());
    assert_eq!(gb2.len(), 6);
    assert!(gb2.verify(None).is_empty());
}

#[test]
fn sl2_pbw_theorem() {
    let (alg, rels) = relations::sl2::<Q>();
    let gb = GroebnerBasis::compute(rels.clone(), &GroebnerOptions::default());
    assert!(gb.is_complete());
    // PBW: the commutation relations already form a Gröbner basis
    assert_eq!(gb.len(), 3);
    for r in &rels {
        assert!(gb.contains(r));
        assert!(gb.elements().contains(&r.monic()));
    }
    let q = QuotientAlgebra::new(gb.clone());
    assert_eq!(q.hilbert_series(4), vec![1, 3, 6, 10, 15]);
    // Casimir element is central
    let casimir = rat(&alg, "e*f + f*e + 1/2*h*h");
    for g in ["e", "f", "h"] {
        assert!(
            gb.reduce_commutator(&casimir, &rat(&alg, g)).is_zero(),
            "Casimir must commute with {}",
            g
        );
    }
}

